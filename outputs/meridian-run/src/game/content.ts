export function getTrafficDimensions(variant: number) {
  const k = variant % 5;
  return {
    width: k === 3 ? 2.5 : 2.05,
    length: k === 3 ? 7.2 : k === 4 ? 5.6 : 4.3,
    bodyHeight: k === 3 ? 2.6 : k === 4 ? 2 : 1.15,
  };
}
